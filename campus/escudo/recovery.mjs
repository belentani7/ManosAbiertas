export function getRecoveryPlan(id,lang='pt'){
 if(!LOCALES.includes(lang))throw new RangeError('Unsupported language');
 const plan=RECOVERY_PLANS.find(p=>p.id===id);
 if(!plan)throw new RangeError('Unknown scenario');
 return {id:plan.id,name:plan.title[lang],steps:plan.steps.map(x=>x[lang])};
}
export function recoveryText(id,lang='pt'){
 const p=getRecoveryPlan(id,lang),l=RECOVERY_LABELS[lang];
 return [l.title,p.name,'',l.steps,...p.steps.map((step,i)=>(i+1)+'. '+step),'',l.warning,'','Manos Abiertas · offline learning material · no personal information'].join('\n');
}
