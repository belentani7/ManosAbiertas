/* Whitelist-publish only intentional, open educational campus assets.
 * Next.js serves the source campus via /campus/* when pnpm build runs.
 * No .env, repository reports, private files, backups, or arbitrary directories.
 */
import {copyFileSync,existsSync,lstatSync,mkdirSync,writeFileSync} from 'node:fs';
import {dirname,join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const ROOT=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const SOURCE=join(ROOT,'campus');
const DESTINATION=join(ROOT,'public','campus');
const MARKER=join(DESTINATION,'.generated-by-manos-build');

export function publicCampusPaths(){
 const paths=['index.html','manifest.webmanifest','tokens.css','app.js','sw.js','course-core.mjs','course-viewer.mjs','escudo/index.html','escudo/core.mjs','escudo/recovery.mjs'];
 for(const [slug,weeks] of [['alfabetizacion-ia',3],['office-sin-miedo',3],['falsos-amigos-pt-es',4]]){
  for(const file of ['syllabus.md','recursos.md','quiz.json'])paths.push('cursos/'+slug+'/'+file);
  for(let i=1;i<=weeks;i++)paths.push('cursos/'+slug+'/semana-'+String(i).padStart(2,'0')+'.md');
 }
 for(const locale of ['pt','es','en','ca'])paths.push('voces/'+locale+'/bienvenida.mp3');
 return paths;
}

export function stagePublicCampus(){
 if(existsSync(DESTINATION)&&!existsSync(MARKER)){
  throw new Error('Refusing to modify manually managed public/campus without build marker');
 }
 const resources=publicCampusPaths();
 if(resources.length!==33||new Set(resources).size!==resources.length){
  throw new Error('Campus publish manifest is not deterministic or contains duplicates');
 }
 // Verify ALL assets before touching the public target (fail closed).
 for(const relative of resources){
  if(relative.startsWith('/')||relative.split('/').includes('..')||relative.startsWith('.'))throw new Error('Unsafe campus path');
  const full=join(SOURCE,relative);
  const parts=relative.split('/');let checked=SOURCE;
  for(const p of parts){checked=join(checked,p);if(lstatSync(checked).isSymbolicLink())throw new Error('Refusing symlink: '+relative);}
  const stat=lstatSync(full);
  if(!stat.isFile()||stat.size>16*1024*1024)throw new Error('Not an approved campus asset: '+relative);
 }
 for(const relative of resources){
  const dest=join(DESTINATION,relative);mkdirSync(dirname(dest),{recursive:true});
  copyFileSync(join(SOURCE,relative),dest);
 }
 writeFileSync(MARKER,'Generated by scripts/prepare-public-campus.mjs. Source of truth: /campus.\n');
 console.log('Next public campus staged: '+resources.length+' vetted educational resources');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url))stagePublicCampus();
